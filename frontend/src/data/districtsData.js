const generate30DayHistory = (baseRisk, baseDengue, baseCholera, baseMalaria, baseRain, baseTemp, baseHum) => {
  const history = [];
  const today = new Date();
  
  for (let i = 29; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];
    
    // Controlled seasonal variance
    const variance = Math.sin(i / 4) * 8 + (Math.random() * 4 - 2);
    const risk = Math.min(100, Math.max(10, Math.round(baseRisk + variance)));
    const dengue = Math.max(0, Math.round(baseDengue + (variance * 0.6) + Math.random() * 3));
    const cholera = Math.max(0, Math.round(baseCholera + (variance * 0.3) + Math.random() * 2));
    const malaria = Math.max(0, Math.round(baseMalaria + (variance * 0.2) + Math.random() * 2));
    const rainfall = Math.max(0, Math.round((baseRain + (variance * 1.5)) * 10) / 10);
    const temperature = Math.round((baseTemp + (Math.cos(i / 5) * 2)) * 10) / 10;
    const humidity = Math.min(98, Math.max(35, Math.round(baseHum + (variance * 0.8))));

    history.push({
      day: 30 - i,
      date: dateStr,
      shortDate: `${d.getDate()}/${d.getMonth() + 1}`,
      riskScore: risk,
      dengue,
      cholera,
      malaria,
      totalCases: dengue + cholera + malaria,
      rainfall,
      temperature,
      humidity
    });
  }
  return history;
};

